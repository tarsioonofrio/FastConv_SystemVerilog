#!/usr/bin/env python3
"""Gera o RTL do bsh16 com 25 multiplicadores em 2 estados de multiplicação a partir do RTL subexpression de 7 multiplicadores.

Os 49 produtos não são múltiplo de 2, e 25 lanes dividem a linha 3 do Hadamard entre os dois estados:

    estado 0: linhas 0, 1, 2 inteiras (lanes 0..20) e colunas 0..3 da linha 3 (lanes 21..24)
    estado 1: linhas 4, 5, 6 inteiras (lanes 0..20) e colunas 4..6 da linha 3 (lanes 21..23); a lane 24 fica parada

O grupo g = 0..2 da inversa recebe as lanes 7g..7g+6 nos dois estados (linhas g e g+4), como no RTL de 28 multiplicadores. O grupo 3
só soma no estado 1: as colunas 0..3 da linha 3 ficam em r_row3_hold, um registrador de 4 palavras. Nos pesos, só as lanes 21..23
mudam de coluna entre os estados, e o grupo 3 mantém a linha 3 habilitada nos dois.

    python3 rtl/conv4x4/data/bsh16/gen_m25.py     # na raiz do repositório
"""
import pathlib

D = pathlib.Path("rtl/conv4x4")
ORIG = D / "conv-bsh16-i60-h16-t14-o16-m07-stream14-prefetch24-rowconst7-subexpression-round-column.sv"
NOVO = D / "conv-bsh16-i60-h16-t14-o16-m25-2state-prefetch24-rowconst7-subexpression-round-column.sv"
s = ORIG.read_text()


def troca(a, b):
    global s
    assert s.count(a) == 1, a
    s = s.replace(a, b)


troca("""   Adapted from the WPN16 row-constant streaming controller for the 7-product
   bit-shift-ternary F(4,3) identity (HADAMARD_SIZE = 7, NUM_MULT = 7).  The control
   structure is unchanged; only the constant row transform, the inverse row
   transform and the geometry defaults follow the bsh16 matrices.
""", """   25 multipliers, two multiplication states (generated by data/bsh16/gen_m25.py).
   State 0: rows 0-2 (lanes 0-20) and columns 0-3 of row 3 (lanes 21-24).
   State 1: rows 4-6 (lanes 0-20) and columns 4-6 of row 3 (lanes 21-23); lane 24 idles.
""")
troca("""    // Number of parallel multipliers; must be a whole number of Hadamard rows.
    parameter int unsigned NUM_MULT            = 7,""", """    // Fixed by this variant: 25 multipliers in two states.
    parameter int unsigned NUM_MULT            = 25,""")
troca("  localparam int unsigned ROWS_PER_CYCLE = FIXED_NUM_MULT / HADAMARD_SIZE;\n",
      "  // Inverse and weight-transform groups; group 3 only serves row 3.\n  localparam int unsigned ROWS_PER_CYCLE = 4;\n")
troca("""  // NUM_MULT only has to be a whole number of Hadamard rows.  It does not have
  // to divide the 49 products: when it does not, the last row batch is partial.
  if ((NUM_MULT < HADAMARD_SIZE) || ((NUM_MULT % HADAMARD_SIZE) != 0)) begin: NUM_MULT_CHECK
    $error("NUM_MULT (%0d) must be a positive whole number of Hadamard rows", NUM_MULT);
  end
""", """  if ((NUM_MULT != 25) || (HADAMARD_SIZE != 7)) begin: NUM_MULT_CHECK
    $error("this variant requires NUM_MULT = 25 and HADAMARD_SIZE = 7 (got %0d, %0d)", NUM_MULT, HADAMARD_SIZE);
  end
""")
troca("  logic [PRODUCT_INDEX_WIDTH-1:0] r_transform_product_idx;\n",
      "  // Columns 0-3 of Hadamard row 3 (state 0), held until the state 1 products arrive.\n  logic [NBITS-1:0] r_row3_hold [3:0];\n")
troca("  logic [NBITS-1:0] w_inverse_partial_current [FIXED_NUM_MULT/HADAMARD_SIZE*CONV_OUTPUT_SIZE-1:0];",
      "  logic [NBITS-1:0] w_inverse_partial_current [ROWS_PER_CYCLE*CONV_OUTPUT_SIZE-1:0];")
troca("      r_inverse_row_idx <= '0;\n      r_transform_product_idx <= '0;\n    end else begin",
      "      r_inverse_row_idx <= '0;\n      r_row3_hold <= '{default: '0};\n    end else begin")
troca("          r_inverse_row_idx     <= '0;\n          r_transform_product_idx <= '0;\n", "          r_inverse_row_idx     <= '0;\n")
i, j = s.index("          r_transform_product_idx <= r_transform_product_idx + PRODUCT"), s.index("          // Register the current Hadamard products.")
s = s[:i] + """          // Capture the state 1 batch at the end of state 0.
          if (r_conv_multiply_count < $bits(r_conv_multiply_count)'(STREAM_CYCLES - 1)) begin
            for (int unsigned lane = 0; lane < FIXED_NUM_MULT; lane++) begin
              if (lane < 21) begin
                r_transform_feature_reg[lane] <= w_conv_transform[28 + lane];
                r_input_weight[lane] <= w_weight_batch[lane / HADAMARD_SIZE][lane % HADAMARD_SIZE];
              end else if (lane < 24) begin
                r_transform_feature_reg[lane] <= w_conv_transform[25 + lane - 21];
                r_input_weight[lane] <= w_weight_batch[3][4 + lane - 21];
              end else begin
                r_transform_feature_reg[lane] <= '0;
                r_input_weight[lane] <= '0;
              end
            end
          end
          // Keep columns 0-3 of row 3 for the inverse of state 1.
          if (r_hadamard_product_valid && (r_hadamard_product_row_idx_reg == '0))
            for (int unsigned c = 0; c < 4; c++)
              r_row3_hold[c] <= r_hadamard_product_reg[21 + c];
""" + s[j:]
i, j = s.index("    end else if ((st_conv_current == HADAMARD) &&\n                 (r_conv_multiply_count < $bits(r_conv_multiply_count)'(STREAM_CYCLES - 1))) begin\n      next_row_base"), s.index("  // Each instance contains only one constant row of the weight transform.")
s = s[:i] + """    end else if ((st_conv_current == HADAMARD) &&
                 (r_conv_multiply_count < $bits(r_conv_multiply_count)'(STREAM_CYCLES - 1))) begin
      // State 1 uses rows 4-6 (groups 0-2) and row 3 again (group 3).
      w_weight_row_enable[3] = 1'b1;
      w_weight_row_enable[4] = 1'b1;
      w_weight_row_enable[5] = 1'b1;
      w_weight_row_enable[6] = 1'b1;
    end
  end

""" + s[j:]
troca("""    int unsigned next_row_base;
    next_row_base = 0;
    w_weight_row_enable = '0;""", "    w_weight_row_enable = '0;")
troca("""      assign inverse_input_row[column] =
          w_inverse_product_rows[group * HADAMARD_SIZE + column];
""", """      if (group < 3)
        assign inverse_input_row[column] = w_inverse_product_rows[group * HADAMARD_SIZE + column];
      else if (column < 4)
        assign inverse_input_row[column] = r_row3_hold[column];
      else
        assign inverse_input_row[column] = w_inverse_product_rows[21 + column - 4];
""")
troca("      row_index = int'(inverse_row_idx) + batch;\n",
      "      // Group 3 is row 3 and only adds with the state 1 batch (index 4).\n"
      "      if (batch == 3) row_index = (int'(inverse_row_idx) == 4) ? 3 : HADAMARD_SIZE;\n"
      "      else row_index = int'(inverse_row_idx) + batch;\n")
NOVO.write_text(s)
print(NOVO)
