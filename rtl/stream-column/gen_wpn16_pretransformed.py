#!/usr/bin/env python3
"""Generate the WPN16 pretransformed-weight RTL from the active m32 core.

The WPN16 package stores the integer-truncated 8x8 weight transforms directly
after the feature maps. This generator changes the active row-constant design
to load those 64 values over the existing six-word column interface.
"""

from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "conv4x4/conv-wpn16-i60-h41-t64-o16-m32-stream16-prefetch24-rowconst8-trunc-column.sv"
DESTINATION = ROOT / "conv4x4/conv-wpn16-i60-h41-t64-o16-m32-stream16-prefetch24-pretransformed-column.sv"


def replace_once(text: str, old: str, new: str) -> str:
    count = text.count(old)
    if count != 1:
        raise ValueError(f"expected exactly one occurrence, found {count}: {old[:100]!r}")
    return text.replace(old, new, 1)


def replace_section(text: str, begin: str, end: str, replacement: str) -> str:
    start = text.index(begin)
    stop = text.index(end, start)
    return text[:start] + replacement + text[stop:]


def main() -> None:
    text = SOURCE.read_text()
    text = replace_once(
        text,
        "/*\n   CONVOLUTION CONTROLLER - streaming fast convolution, truncated weight transform,\n   column interface, a configurable integer number of Hadamard rows per cycle.\n\n   Algorithm: wpn16   input tile 6x6   Hadamard 8x8   output tile 4x4\n   Generated by rtl/stream-column/gen_stream_column.py from\n   the algorithm build.json; do not edit by hand.  Control structure derived from\n   conv-i24-h13-t08-o4-m04-stream08-prefetch8-rowconst4-trunc-column.sv (conv2x2).\n*/",
        "/*\n   WPN16 streaming column convolution with pretransformed integer weights.\n\n   Algorithm: wpn16   input tile 6x6   Hadamard 8x8   output tile 4x4\n   Generated by rtl/stream-column/gen_wpn16_pretransformed.py from the active\n   WPN16 m32 row-constant RTL and the canonical integer-transformed package.\n*/",
    )

    text = replace_once(
        text,
        "  // Raw spatial weights are retained for the tile. ROWS_PER_CYCLE transformed\n  // rows are held in the MAC weight bank for each Hadamard batch.\n  localparam int RAW_WEIGHT_WORDS = CONV_KERNEL_SIZE * CONV_KERNEL_SIZE;\n  localparam int RAW_WEIGHT_COUNT_WIDTH = f_width_min1(RAW_WEIGHT_WORDS);\n  localparam int RAW_WEIGHT_BASE = (N_CHANNEL_IN * FEAT_INPUT_SIZE * FEAT_INPUT_WIDTH) +\n                                   (N_CHANNEL_IN * N_CHANNEL_OUT * WEIGHT_CYCLES);",
        "  // The canonical WPN16 package stores each truncated 8x8 transformed kernel\n  // after the feature maps. The six-word column port needs eleven beats; the last\n  // beat contains two padding words that are ignored.\n  localparam int PRETRANSFORMED_WEIGHT_WORDS = HADAMARD_SIZE * HADAMARD_SIZE;\n  localparam int PRETRANSFORMED_WEIGHT_COUNT_WIDTH =\n      f_width_min1(PRETRANSFORMED_WEIGHT_WORDS + CONV_INPUT_SIZE);\n  localparam int WEIGHT_READ_BEATS =\n      (PRETRANSFORMED_WEIGHT_WORDS + CONV_INPUT_SIZE - 1) / CONV_INPUT_SIZE;\n  localparam int WEIGHT_LAST_BEAT_OFFSET = (WEIGHT_READ_BEATS - 1) * CONV_INPUT_SIZE;\n  localparam int PRETRANSFORMED_WEIGHT_BASE =\n      N_CHANNEL_IN * FEAT_INPUT_SIZE * FEAT_INPUT_WIDTH;",
    )
    text = replace_once(
        text,
        "  // The spatial weights are retained for the complete tile. The MAC weight\n  // bank holds ROWS_PER_CYCLE transformed rows for the active batch.\n  logic signed [NBITS-1:0] r_weight_spatial[RAW_WEIGHT_WORDS-1:0];\n  logic [NBITS-1:0] r_input_weight[FIXED_NUM_MULT-1:0];\n  localparam WEIGHT_ROW_COUNT_WIDTH = RAW_WEIGHT_COUNT_WIDTH;",
        "  // Cache the complete pretransformed 8x8 kernel, then select the rows needed\n  // by each batch of MAC lanes. No weight-transform datapath is instantiated.\n  logic signed [NBITS-1:0] r_weight_pretransformed[PRETRANSFORMED_WEIGHT_WORDS-1:0];\n  logic [NBITS-1:0] r_input_weight[FIXED_NUM_MULT-1:0];\n  localparam WEIGHT_ROW_COUNT_WIDTH = PRETRANSFORMED_WEIGHT_COUNT_WIDTH;",
    )
    text = replace_once(
        text,
        "  // One constant-row transform per Hadamard row.  Only one enable is asserted\n  // per cycle by the convolution FSM; inactive rows drive zero (operand isolation).\n  logic [NBITS-1:0] w_weight_row [HADAMARD_SIZE-1:0][HADAMARD_SIZE-1:0];\n  logic [HADAMARD_SIZE-1:0] w_weight_row_enable;",
        "  // Matrix view of the cached, pretransformed integer weight tile.\n  logic [NBITS-1:0] w_weight_row [HADAMARD_SIZE-1:0][HADAMARD_SIZE-1:0];",
    )

    text = text.replace("NADDR'(RAW_WEIGHT_BASE)", "NADDR'(PRETRANSFORMED_WEIGHT_BASE)")
    text = text.replace("NADDR'(RAW_WEIGHT_WORDS)", "NADDR'(PRETRANSFORMED_WEIGHT_WORDS)")
    text = replace_once(
        text,
        "      // Restart at the first raw-weight vector.  Each vector contains one row\n      // of the 3x3 kernel.\n      r_input_addr_kernel <= r_input_addr_kernel_base;\n    end else if (st_input_current == READ_WEIGHTS) begin\n      r_input_addr_kernel <= r_input_addr_kernel + NADDR'(CONV_KERNEL_SIZE);",
        "      // Restart at the first beat of the pretransformed 8x8 kernel.\n      r_input_addr_kernel <= r_input_addr_kernel_base;\n    end else if (st_input_current == READ_WEIGHTS) begin\n      r_input_addr_kernel <= r_input_addr_kernel + NADDR'(CONV_INPUT_SIZE);",
    )
    text = text.replace(
        "WEIGHT_ROW_COUNT_WIDTH'(RAW_WEIGHT_WORDS - CONV_KERNEL_SIZE)",
        "WEIGHT_ROW_COUNT_WIDTH'(WEIGHT_LAST_BEAT_OFFSET)",
    )
    text = replace_once(
        text,
        "  // r_weight_row_count:          raw spatial words read for the active weight tile",
        "  // r_weight_row_count:          transformed weight words loaded for the active tile",
    )
    text = replace_once(
        text,
        "          r_weight_row_count <= r_weight_row_count + WEIGHT_ROW_COUNT_WIDTH'(CONV_KERNEL_SIZE);",
        "          r_weight_row_count <= r_weight_row_count + WEIGHT_ROW_COUNT_WIDTH'(CONV_INPUT_SIZE);",
    )
    text = replace_once(
        text,
        "        // The first tile remains here while the nine raw weights are read.",
        "        // The first tile remains here while the pretransformed weight tile is read.",
    )
    text = replace_once(
        text,
        "          // Capture the first transformed weight batch after the raw spatial\n          // tile is complete. TRANSFORM is held during the first weight read.",
        "          // Capture the first batch after the pretransformed weight tile is complete.",
    )
    text = replace_once(
        text,
        "          // Capture the next transformed row batch at the same pipeline\n          // boundary used by the feature transform. Current weights remain\n          // active through this edge; the next batch is used in the next cycle.",
        "          // Capture the next pretransformed row batch at the same pipeline\n          // boundary used by the feature transform. Current weights remain\n          // active through this edge; the next batch is used in the next cycle.",
    )

    text = replace_section(
        text,
        "  always_ff @(posedge clk or posedge reset) begin: WEIGHT_REG_BLOCK",
        "  // ----------------------------------------------------------------------------------------------------\n  // -------  PART 3 - CONVOLUTION CONTROL",
        "  always_ff @(posedge clk or posedge reset) begin: WEIGHT_REG_BLOCK\n"
        "    if (reset) begin\n"
        "      for (int unsigned i = 0; i < PRETRANSFORMED_WEIGHT_WORDS; i++)\n"
        "        r_weight_pretransformed[i] <= '0;\n"
        "    end else if (st_input_current == READ_WEIGHTS && p_input_valid) begin\n"
        "      for (int unsigned lane = 0; lane < CONV_INPUT_SIZE; lane++) begin\n"
        "        if ((int'(r_weight_row_count) + lane) < PRETRANSFORMED_WEIGHT_WORDS)\n"
        "          r_weight_pretransformed[int'(r_weight_row_count) + lane] <=\n"
        "              $signed(p_input_data[lane*NBITS +: NBITS]);\n"
        "      end\n"
        "    end\n"
        "  end\n\n",
    )

    text = replace_section(
        text,
        "  // Enable the constant weight-transform rows required by the active batch:",
        "  for (genvar lane = 0; lane < FIXED_NUM_MULT; lane++) begin: MAC_LANES",
        "  // Expose the packed pretransformed 8x8 tile as a row/column matrix.\n"
        "  for (genvar row = 0; row < HADAMARD_SIZE; row++) begin: PRETRANSFORMED_WEIGHT_ROWS\n"
        "    for (genvar column = 0; column < HADAMARD_SIZE; column++) begin: PRETRANSFORMED_WEIGHT_COLUMNS\n"
        "      assign w_weight_row[row][column] =\n"
        "          r_weight_pretransformed[row * HADAMARD_SIZE + column];\n"
        "    end\n"
        "  end\n\n",
    )

    # The generated constant-transform module is no longer used by this variant.
    text = replace_section(
        text,
        "// -----------------------------------------------------------------------------\n// Constant-row transform of the 3x3 spatial kernel.",
        "// -----------------------------------------------------------------------------\n// Row-streamed inverse transform.",
        "",
    )
    DESTINATION.write_text(text)
    print(DESTINATION)


if __name__ == "__main__":
    main()
